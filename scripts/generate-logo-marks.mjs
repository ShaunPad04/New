/**
 * Generates `src/lib/logo-marks.ts` from simple-icons.
 *
 * The marks are inlined as path data rather than shipped as files: the strip
 * is server-rendered, so inlining costs no JavaScript and no extra requests,
 * and `fill="currentColor"` means every mark takes exactly one colour from its
 * parent — which is the whole point of a logo row.
 *
 * simple-icons is a devDependency and never reaches the client bundle.
 *
 * These are third-party trademarks. They appear under "the stack we build on",
 * which is nominative use — naming a tool we build with. They must never be
 * moved under a claim that implies those companies are clients or endorsers.
 *
 * Run: node scripts/generate-logo-marks.mjs
 */
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

const WANTED = [
  // Stack strip
  "nextdotjs", "react", "typescript", "tailwindcss", "nodedotjs",
  "vercel", "github", "figma", "notion", "claude", "nvidia",
  "greensock", "shopify", "googleanalytics",
  // Footer socials.
  //
  // Only accounts that actually exist. X and Behance were dropped on
  // 2026-09-15 — they had never had a profile behind them, and an unset
  // entry still renders a ring a thumb tries to press.
  //
  // LinkedIn is absent for the same reason OpenAI is: it is not in
  // simple-icons, because the trademark holder asked to be removed. It needs
  // the official asset from LinkedIn's own brand pages, used under their brand
  // guidelines — not a hand-drawn approximation.
  "instagram", "facebook", "tiktok",
];

const entries = WANTED.map((slug) => {
  const key = "si" + slug[0].toUpperCase() + slug.slice(1);
  const icon = si[key];
  if (!icon) throw new Error(`simple-icons has no icon for "${slug}"`);
  return [slug, icon];
});

const body = entries
  .map(([slug, i]) => `  "${slug}": {\n    title: ${JSON.stringify(i.title)},\n    path: ${JSON.stringify(i.path)},\n  },`)
  .join("\n");

writeFileSync(
  "src/lib/logo-marks.ts",
  `// GENERATED by scripts/generate-logo-marks.mjs — do not edit by hand.
//
// Third-party trademarks, inlined as 24x24 single-path glyphs so they render
// in one colour from \`currentColor\`. Displayed under "the stack we build on",
// which is nominative use. Never move them under a claim of endorsement.

export type LogoMark = { title: string; path: string };

export const LOGO_MARKS: Record<string, LogoMark> = {
${body}
};
`
);

/*
 * THE SAME MARKS AS AN EXTERNAL SPRITE (2026-09-17).
 *
 * `LogoCloud` used to inline a <symbol> sprite in the HTML. Measured on the
 * homepage: 23 KB raw, 10 KB gzipped, and because the strip is a server
 * component the same markup sat in the RSC payload a second time — about
 * 20 KB of a 71 KB gzipped document, all on the critical path for a strip
 * that is below the fold. The strip now references `/logo-marks.svg#id`,
 * which the browser fetches once, off the critical path, and caches.
 * The ids match `markId()` in logo-cloud.tsx; keep them in step.
 */
const sprite =
  `<svg xmlns="http://www.w3.org/2000/svg">\n` +
  entries
    .map(
      ([slug, i]) =>
        `  <symbol id="logo-mark-${slug}" viewBox="0 0 24 24"><path d="${i.path}"/></symbol>`,
    )
    .join("\n") +
  `\n</svg>\n`;
writeFileSync("public/logo-marks.svg", sprite);

console.log(`wrote ${entries.length} marks and public/logo-marks.svg`);
